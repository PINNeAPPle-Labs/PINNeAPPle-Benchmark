"""Paths of experiment 09; puts the PINNeAPPle library (checked out next to this repository) on the path."""
from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIB = ROOT.parents[2] / "PINNeAPPle"
sys.path.insert(0, str(LIB))

DATA = ROOT / "data"          # artifacts of the first runs, adopted by bench09.migrate (regenerated by prepare if absent)
RES = ROOT / "results"
for d in (DATA, RES, RES / "runs"):
    d.mkdir(parents=True, exist_ok=True)
os.environ.setdefault("OMP_NUM_THREADS", "1")
